namespace Frappe.Analyzers.UnitTests;

/// <summary>FRP003 (CRAFT-10): every suppression in code states its reason.</summary>
public sealed class JustifiedSuppressionAnalyzerTests
{
    [Test]
    [Arguments("[SuppressMessage(\"Usage\", \"CA2225\")]")]
    [Arguments("[SuppressMessage(\"Usage\", \"CA2225\", Justification = \"\")]")]
    [Arguments("[SuppressMessage(\"Usage\", \"CA2225\", Justification = \"  \")]")]
    [Arguments("[UnconditionalSuppressMessage(\"Trimming\", \"IL2026\")]")]
    public async Task A_suppression_attribute_without_a_justification_is_reported(string attribute)
    {
        // Arrange
        var source = $$"""
            using System.Diagnostics.CodeAnalysis;

            /// <summary>A sample type.</summary>
            public static class Sample
            {
                {{attribute}}
                public static void Run() { }
            }
            """;

        // Act
        var diagnostics = await AnalyzerRun.DiagnosticsOf(new JustifiedSuppressionAnalyzer(), source);

        // Assert
        await Assert.That(diagnostics.Select(d => d.Id)).IsEquivalentTo(["FRP003"]);
    }

    [Test]
    public async Task A_suppression_attribute_with_a_justification_is_not_reported()
    {
        // Arrange
        const string source = """
            using System.Diagnostics.CodeAnalysis;

            /// <summary>A sample type.</summary>
            public static class Sample
            {
                [SuppressMessage("Usage", "CA2225", Justification = "CRAFT-10: the operators are the rule language.")]
                public static void Run() { }
            }
            """;

        // Act
        var diagnostics = await AnalyzerRun.DiagnosticsOf(new JustifiedSuppressionAnalyzer(), source);

        // Assert
        await Assert.That(diagnostics).IsEmpty();
    }

    [Test]
    [Arguments("")]
    [Arguments("    /// <summary>Runs.</summary>")]
    public async Task A_pragma_that_disables_a_warning_without_a_comment_is_reported(string lineAbove)
    {
        // Arrange
        var source = $$"""
            /// <summary>A sample type.</summary>
            public static class Sample
            {
            {{lineAbove}}
            #pragma warning disable CA1031
                public static void Run() { }
            #pragma warning restore CA1031
            }
            """;

        // Act
        var diagnostics = await AnalyzerRun.DiagnosticsOf(new JustifiedSuppressionAnalyzer(), source);

        // Assert
        await Assert.That(diagnostics.Select(d => d.Id)).IsEquivalentTo(["FRP003"]);
    }

    [Test]
    [Arguments("#pragma warning disable CA1031 // Any failure leaves the check unanswered.")]
    [Arguments("// EF Core materializes the aggregate through its private constructor.\n#pragma warning disable CA1031")]
    public async Task A_pragma_with_its_reason_on_the_same_line_or_the_line_above_is_not_reported(string pragma)
    {
        // Arrange
        var source = $$"""
            {{pragma}}
            /// <summary>A sample type.</summary>
            public static class Sample
            {
                public static void Run() { }
            }
            """;

        // Act
        var diagnostics = await AnalyzerRun.DiagnosticsOf(new JustifiedSuppressionAnalyzer(), source);

        // Assert
        await Assert.That(diagnostics).IsEmpty();
    }

    [Test]
    public async Task A_pragma_in_generated_code_is_not_reported()
    {
        // Arrange
        const string source = """
            // <auto-generated />
            using System;

            #pragma warning disable 612, 618
            /// <summary>A sample type.</summary>
            public static class Sample
            {
                public static void Run() { }
            }
            """;

        // Act
        var diagnostics = await AnalyzerRun.DiagnosticsOf(new JustifiedSuppressionAnalyzer(), source);

        // Assert
        await Assert.That(diagnostics).IsEmpty();
    }
}
