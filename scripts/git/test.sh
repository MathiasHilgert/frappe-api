#!/usr/bin/env bash
# shellcheck disable=SC2016 # bash -c snippets expand their own positional args
# Self-contained tests for scripts/git/*. Builds throwaway repos under mktemp -d.
# Usage: scripts/git/test.sh   (set SKIP_DOCKER=1 to skip the commitlint cases)
set -uo pipefail

dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
failures=0

expect() { # expect <pass|fail|usage> <description> <command...>
  local want="$1" desc="$2"; shift 2
  local out code
  out="$("$@" 2>&1)"; code=$?
  if { [[ "$want" == pass ]] && [[ $code -eq 0 ]]; } || { [[ "$want" == fail ]] && [[ $code -eq 1 ]]; } \
     || { [[ "$want" == usage ]] && [[ $code -eq 2 ]]; }; then
    echo "ok   - $desc"
  else
    echo "FAIL - $desc (want $want, exit $code)"; printf '       %s\n' "$out"
    failures=$((failures + 1))
  fi
}

commit() { git -C "$repo" -c user.name=t -c user.email=t@example.com commit -q --allow-empty -m "$1"; }

# --- check-branch.sh ---
for b in main feat/table-reservations fix/123-null-total chore/abc-42-bump-sdk \
         dependabot/nuget/Npgsql-9.0.1 release/v1.4.0 release/v2.0.0-rc.1; do
  expect pass "branch '$b'" "$dir/check-branch.sh" "$b"
done
for b in feature/foo feat/Foo feat/foo_bar feat/ fix/foo--bar master release/1.0 release/v1.0 random; do
  expect fail "branch '$b'" "$dir/check-branch.sh" "$b"
done
expect pass "branch from GITHUB_HEAD_REF" env GITHUB_HEAD_REF=docs/readme "$dir/check-branch.sh"
expect fail "bad GITHUB_HEAD_REF" env GITHUB_HEAD_REF=Bad "$dir/check-branch.sh"

# --- check-ai-attribution.sh text ---
text_case() { # text_case <pass|fail> <desc> <text>
  printf '%s\n' "$3" >"$tmp/t.txt"
  expect "$1" "text file: $2" "$dir/check-ai-attribution.sh" text "$tmp/t.txt"
  expect "$1" "text stdin: $2" bash -c 'printf "%s\n" "$1" | "$2" text -' _ "$3" "$dir/check-ai-attribution.sh"
}
text_case pass "plain body" $'feat: add tables\n\nAdds the table model.'
text_case pass "mentions openai in a dependency bump" "build(deps): bump openai from 1.2.0 to 1.3.0"
text_case pass "human co-author" "Co-authored-by: Ana Perez <ana@example.com>"
text_case fail "Claude co-author trailer" "Co-authored-by: Claude Opus <noreply@anthropic.com>"
text_case fail "copilot bot email" "co-authored-by: bot <copilot@github.com>"
text_case fail "Cursor co-author" "Co-Authored-By: Cursor Agent <agent@example.com>"
text_case fail "robot generated with Claude Code" $'Summary\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)'
text_case fail "body with robot generated with Claude Code (plain)" $'Body\n🤖 Generated with Claude Code'
text_case fail "generated by Copilot" "Generated by Copilot"
text_case fail "AI-generated" "This change is AI-Generated."

# --- check-ai-attribution.sh commits ---
repo="$tmp/repo"; git init -q -b main "$repo"
commit "chore: init"
commit "build(deps): bump openai from 1.2.0 to 1.3.0"
commit $'feat: tables\n\nCo-authored-by: Ana <ana@example.com>'
good_head="$(git -C "$repo" rev-parse HEAD)"
commit $'fix: thing\n\nCo-Authored-By: Claude <noreply@anthropic.com>'
expect pass "commits without attribution (false-positive guard)" \
  bash -c 'cd "$1" && "$2" commits HEAD~3 "$3"' _ "$repo" "$dir/check-ai-attribution.sh" "$good_head"
expect fail "commits with Claude trailer" \
  bash -c 'cd "$1" && "$2" commits HEAD~3 HEAD' _ "$repo" "$dir/check-ai-attribution.sh"
out="$(cd "$repo" && "$dir/check-ai-attribution.sh" commits HEAD~1 HEAD 2>&1)"
sha="$(git -C "$repo" rev-parse --short=12 HEAD)"
if [[ "$out" == *"$sha line 3:"* ]]; then echo "ok   - report names SHA and line"; else
  echo "FAIL - report names SHA and line: $out"; failures=$((failures + 1)); fi
expect usage "bad mode" "$dir/check-ai-attribution.sh" nope
expect usage "unknown ref is an error, not a silent pass" \
  bash -c 'cd "$1" && "$2" commits does-not-exist HEAD' _ "$repo" "$dir/check-ai-attribution.sh"

# --- hooks/commit-msg ---
hook_case() {
  printf '%s\n' "$3" >"$tmp/msg"
  expect "$1" "hook: $2" "$dir/hooks/commit-msg" "$tmp/msg"
}
hook_case pass "conventional" "feat(api): add tables"
hook_case pass "breaking" "refactor!: drop v1 endpoints"
hook_case pass "merge commit" "Merge branch 'main' into feat/x"
hook_case fail "not conventional" "Add tables"
hook_case fail "unknown type" "feature: add tables"
hook_case fail "too long" "feat: $(printf 'a%.0s' {1..100})"
hook_case fail "AI trailer" $'feat: add tables\n\nCo-authored-by: Claude <noreply@anthropic.com>'

# --- hooks/pre-commit ---
pre="$tmp/pre"; git init -q -b main "$pre"
printf 'x\n' >"$pre/notes.md"; git -C "$pre" add notes.md
expect pass "pre-commit: nothing staged in C# skips dotnet format" bash -c 'cd "$1" && "$2"' _ "$pre" "$dir/hooks/pre-commit"
printf 'class A{}\n' >"$pre/A.cs"; git -C "$pre" add A.cs
expect fail "pre-commit: staged C# outside a solution fails loudly" \
  bash -c 'cd "$1" && PATH=/usr/bin:/bin FRAPPE_DOTNET=false "$2"' _ "$pre" "$dir/hooks/pre-commit"

# --- lint-commits.sh (Docker) ---
if [[ "${SKIP_DOCKER:-0}" != 1 ]]; then
  lint="$tmp/lint"; git init -q -b main "$lint"; repo="$lint"
  commit "chore: init"
  commit "feat: good commit"
  good="$(git -C "$lint" rev-parse HEAD)"
  commit "Bad commit message"
  expect pass "commitlint good range" bash -c 'cd "$1" && "$2" HEAD~1 "$3"' _ "$lint" "$dir/lint-commits.sh" "$good"
  expect fail "commitlint range with a bad commit" bash -c 'cd "$1" && "$2" HEAD~2 HEAD' _ "$lint" "$dir/lint-commits.sh"
  repo="$lint"; commit "Feat: Upper type"
  expect fail "commitlint uppercase type" bash -c 'cd "$1" && "$2" HEAD~1 HEAD' _ "$lint" "$dir/lint-commits.sh"
  # Dependabot pastes release notes into the body; its commits are generated, so only humans are linted.
  long_line="$(printf 'x%.0s' {1..120})"
  repo="$lint"; commit "$(printf 'build(deps): bump foo from 1.0 to 2.0\n\n%s\n\nSigned-off-by: dependabot[bot] <support@github.com>' "$long_line")"
  expect pass "commitlint skips dependabot commits" bash -c 'cd "$1" && "$2" HEAD~1 HEAD' _ "$lint" "$dir/lint-commits.sh"
  repo="$lint"; commit "$(printf 'build: bump foo\n\n%s' "$long_line")"
  expect fail "commitlint still checks human body lines" bash -c 'cd "$1" && "$2" HEAD~1 HEAD' _ "$lint" "$dir/lint-commits.sh"
  # In a worktree .git is a file pointing outside the checkout; linting must not depend on it.
  git -C "$lint" worktree add -q -b wt "$tmp/lint-wt" "$good"
  expect pass "commitlint inside a git worktree" bash -c 'cd "$1" && "$2" HEAD~1 HEAD' _ "$tmp/lint-wt" "$dir/lint-commits.sh"
fi

if [[ $failures -gt 0 ]]; then echo "$failures failure(s)"; exit 1; fi
echo "all tests passed"
